/**
 * Writes CONTENT_REVIEW.md: every visitor-facing Greek string that is NOT the owner's own wording,
 * so the owner can approve it. Run: npm run content-review
 */
import { readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
const { ui } = await import(pathToFileURL(join(root, 'src/i18n/ui.ts')).href);
const { services, portfolio, site } = await import(
  pathToFileURL(join(root, 'src/data/site.ts')).href
);

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const rows = (obj, prefix = '') =>
  Object.entries(obj).flatMap(([k, v]) => {
    const key = prefix ? `${prefix}.${k}` : k;
    if (typeof v === 'string') return [`| \`${key}\` | ${esc(v)} |`];
    if (Array.isArray(v))
      return v.flatMap((item, i) =>
        typeof item === 'string'
          ? [`| \`${key}[${i}]\` | ${esc(item)} |`]
          : rows(item, `${key}[${i}]`),
      );
    if (v && typeof v === 'object') return rows(v, key);
    return [];
  });
const table = (lines) => ['| Key | Text |', '|---|---|', ...lines].join('\n');

const out = [];
out.push('# Content review');
out.push('');
out.push(
  'Every Greek string on the site that is **not** the owner’s own wording, for the owner to approve or edit. ' +
    'The owner’s copy (headline, intro, the nine service titles, the partnership paragraph, the values and the closing line) is used word for word and is not listed. ' +
    'Generated by `npm run content-review` from the source files named in each heading; edit the text there.',
);
out.push('');
out.push('## Shared interface — `src/i18n/ui.ts`');
out.push('');
out.push(table(rows(ui.el)));
out.push('');
out.push('## Business data — `src/data/site.ts`');
out.push('');
out.push(
  table([
    `| \`site.displayName\` | ${esc(site.displayName)} |`,
    ...site.hours.map((h, i) => `| \`site.hours[${i}].label\` | ${esc(h.label.el)} |`),
  ]),
);
out.push('');
out.push('### Services (titles are the owner’s; the rest is new)');
for (const s of services) {
  out.push('');
  out.push(`**${s.text.el.title}** (\`#${s.slug}\`)`);
  out.push('');
  const rest = Object.fromEntries(Object.entries(s.text.el).filter(([k]) => k !== 'title'));
  out.push(table(rows(rest)));
}
out.push('');
out.push('### Portfolio (stand-in titles and alt texts)');
out.push('');
out.push(table(portfolio.flatMap((p) => rows(p.text.el, p.image))));

const pagesDir = join(root, 'src/i18n/pages');
const files = (await readdir(pagesDir).catch(() => [])).filter((f) => f.endsWith('.ts')).sort();
for (const f of files) {
  const mod = await import(pathToFileURL(join(pagesDir, f)).href);
  for (const [name, value] of Object.entries(mod)) {
    if (!value || typeof value !== 'object' || !('el' in value)) continue;
    out.push('');
    out.push(`## \`src/i18n/pages/${f}\` — \`${name}\``);
    out.push('');
    out.push(table(rows(value.el)));
  }
}
out.push('');
out.push('## Other new text');
out.push('');
out.push('- Share image (`public/og.jpg`): the logo and the owner’s tagline only.');
out.push('');

await writeFile(join(root, 'CONTENT_REVIEW.md'), out.join('\n'));
console.log('CONTENT_REVIEW.md written');
